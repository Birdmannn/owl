import { test, expect } from '@playwright/test';
import { injectWallet } from './wallet-fixture';
import { connectThroughPilot, createProfile } from './pilot-flow';
test('Pilot wraps owner connection, creates a profile, and requires explicit permission selection', async ({page,context})=>{
  await injectWallet(context);await page.goto('/');
  await expect(page.getByRole('button',{name:'Fly forward'})).toBeDisabled();
  await connectThroughPilot(page);
  await page.getByRole('textbox',{name:'Username',exact:true}).fill('!!');
  await page.getByRole('button',{name:'Create Pilot profile'}).click();
  await expect(page.getByText(/Use 3–20 characters/)).toBeVisible();
  await createProfile(page);
  const dialog=page.getByRole('dialog',{name:'Sign these on my behalf'});
  await expect(dialog.getByText('@owl_pilot',{exact:true})).toBeVisible();
  await expect(dialog.getByText('Pilot Test Wallet · CKB Testnet',{exact:true})).toBeVisible();
  await expect(dialog.getByRole('button',{name:'Refresh balance ↻'})).toBeVisible();
  const approve=dialog.getByRole('button',{name:'Allow Pilot to sign selected actions'});
  await expect(approve).toBeDisabled();
  await dialog.getByRole('checkbox',{name:/Fly forward/}).check();await expect(approve).toBeEnabled();
  await dialog.getByRole('checkbox',{name:/Fly forward/}).uncheck();await expect(approve).toBeDisabled();
  await dialog.getByText('Inspect app manifest',{exact:true}).click();
  await expect(dialog.locator('.manifest-details pre')).toContainText('counter.increment');
  await expect(dialog.locator('.manifest-details pre')).toContainText('2000000');
  await page.screenshot({path:'test-results/pilot-permissions.png',fullPage:true});
  await page.getByRole('button',{name:'Close Pilot'}).click();
  await expect(page.getByRole('button',{name:'Fly forward'})).toBeDisabled();
  const other=await context.newPage();await other.goto('/');await expect(other.getByText(/Waiting for session access/)).toBeVisible();await other.close();
  await page.reload();await expect(page.getByRole('button',{name:'Enable Pilot'})).toBeEnabled();
  await page.getByRole('button',{name:'Open Pilot'}).click();
  await expect(page.getByRole('dialog',{name:'Sign these on my behalf'})).toBeVisible();
  await expect(page.getByText('@owl_pilot',{exact:true})).toBeVisible();
  await expect(page.getByRole('checkbox',{name:/Fly forward/})).not.toBeChecked();
  await page.keyboard.press('Escape');await expect(page.getByRole('dialog')).not.toBeVisible();
  await page.getByRole('button',{name:'Open Pilot'}).click();
  await page.getByRole('button',{name:'Disconnect owner wallet'}).click();
  await expect(page.getByRole('button',{name:'Connect wallet'}).first()).toBeVisible();
  await connectThroughPilot(page);
  await expect(page.getByRole('button',{name:'Continue as @owl_pilot'})).toBeVisible();
  await page.getByRole('button',{name:'Continue as @owl_pilot'}).click();
  await expect(page.getByRole('dialog',{name:'Sign these on my behalf'})).toBeVisible();
});
test('Pilot modal and demo fit a mobile viewport',async({page,context})=>{
  await injectWallet(context);await page.setViewportSize({width:390,height:844});await page.goto('/');
  await connectThroughPilot(page);await createProfile(page);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
  await page.screenshot({path:'test-results/pilot-mobile.png',fullPage:true});
});
